#!/usr/bin/env node
/**
 * Embeds canonical SQL migrations into a TypeScript module so production
 * bundles never look up migrations on the filesystem at runtime.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = join(repoRoot, "migrations", "private");
const outDir = join(repoRoot, "src", "database", "generated");
const outPath = join(outDir, "platform-migrations.ts");

const filenames = readdirSync(sourceDir)
  .filter((name) => name.endsWith(".sql"))
  .sort((a, b) => a.localeCompare(b, "en", { numeric: true, sensitivity: "base" }));

const migrations = filenames.map((filename) => ({
  filename,
  sql: readFileSync(join(sourceDir, filename), "utf8"),
}));

mkdirSync(outDir, { recursive: true });

const contents = `/* AUTO-GENERATED by scripts/generate-platform-migrations.mjs — do not edit.
 * Canonical source is migrations/private/*.sql
 */
export const PLATFORM_MIGRATIONS: readonly { filename: string; sql: string }[] = ${JSON.stringify(
  migrations,
  null,
  2,
)};
`;

writeFileSync(outPath, contents, "utf8");
console.log(`Wrote ${outPath} (${migrations.length} migration(s))`);
