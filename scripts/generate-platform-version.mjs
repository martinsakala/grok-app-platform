#!/usr/bin/env node
/**
 * Reads the canonical root VERSION file and writes a TypeScript constant
 * consumed by runtime. Runtime must never read VERSION from the filesystem.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const versionPath = join(repoRoot, "VERSION");
const outDir = join(repoRoot, "src", "runtime", "generated");
const outPath = join(outDir, "platform-version.ts");

const version = readFileSync(versionPath, "utf8").trim();
if (!version) {
  throw new Error(`Platform VERSION file is empty: ${versionPath}`);
}
if (!/^\d+\.\d+\.\d+$/.test(version)) {
  throw new Error(`Platform VERSION is not a semver patch triplet: ${JSON.stringify(version)}`);
}

mkdirSync(outDir, { recursive: true });

const contents = `/* AUTO-GENERATED by scripts/generate-platform-version.mjs — do not edit.
 * Canonical source of truth is the repository root VERSION file.
 */
export const PLATFORM_VERSION = ${JSON.stringify(version)};
`;

writeFileSync(outPath, contents, "utf8");
console.log(`Wrote ${outPath} (PLATFORM_VERSION=${version})`);
