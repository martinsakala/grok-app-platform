#!/usr/bin/env node
/**
 * Embeds src/design/gallery/*.md into a TypeScript module.
 * Run with: node --experimental-strip-types scripts/generate-design-gallery.mjs
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { register } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

register("./ts-js-loader.mjs", import.meta.url);

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = join(repoRoot, "src", "design", "gallery");
const outDir = join(repoRoot, "src", "design", "generated");
const outPath = join(outDir, "gallery.ts");

const { parseDesignMd } = await import(new URL("../src/design/parse.ts", import.meta.url).href);

const filenames = readdirSync(sourceDir)
  .filter((name) => name.endsWith(".md"))
  .sort((a, b) => a.localeCompare(b, "en", { numeric: true, sensitivity: "base" }));

const entries = filenames.map((filename) => {
  const markdown = readFileSync(join(sourceDir, filename), "utf8");
  const spec = parseDesignMd(markdown);
  return {
    id: filename.replace(/\.md$/, ""),
    name: spec.brand.name,
    tagline: spec.brand.tagline,
    markdown,
    spec,
  };
});

mkdirSync(outDir, { recursive: true });

const contents = `/* AUTO-GENERATED by scripts/generate-design-gallery.mjs — do not edit.
 * Canonical source is src/design/gallery/*.md
 */
import type { DesignSpec } from "../types.js";

export type DesignGalleryEntry = {
  id: string;
  name: string;
  tagline: string;
  markdown: string;
  spec: DesignSpec;
};

export const DESIGN_GALLERY: readonly DesignGalleryEntry[] = ${JSON.stringify(entries, null, 2)};
`;

writeFileSync(outPath, contents, "utf8");
console.log(`Wrote ${outPath} (${entries.length} preset(s))`);
